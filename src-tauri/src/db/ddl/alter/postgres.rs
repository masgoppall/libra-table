//! ALTER TABLE on Postgres: one statement per change, all in one transaction.

use crate::db::sql::{literal_for, qualified, quote_ident};
use crate::error::AppResult;
use crate::models::Dialect;

use super::super::clauses::{
    column_def, comment_literal, comment_of, create_index, default_expr, fk_clause, need_name,
    need_type, quoted_list, same_default, same_type, sql,
};
use super::super::plan::{Ctx, Step};
use super::super::spec::{AlterOp, ColumnSpec};

const D: Dialect = Dialect::Postgres;

pub(super) fn alter(
    schema: &str,
    table: &str,
    ops: &[AlterOp],
    ctx: &Ctx,
    steps: &mut Vec<Step>,
) -> AppResult<()> {
    let t = qualified(D, schema, table);
    for op in ops {
        match op {
            AlterOp::AddColumn { column } => add_column(&t, column, steps)?,
            AlterOp::DropColumn { name } => sql(
                steps,
                format!("ALTER TABLE {t} DROP COLUMN {}", quote_ident(D, name)),
            ),
            AlterOp::ModifyColumn { original, column } => {
                modify_column(&t, original, column, steps)?
            }
            AlterOp::SetPrimaryKey { columns } => set_primary_key(&t, columns, ctx, steps),
            AlterOp::AddIndex { index } => sql(steps, create_index(D, schema, table, index)?),
            AlterOp::DropIndex { name } => match ctx.index_constraints.get(name) {
                // A UNIQUE or PRIMARY KEY constraint owns the index: drop the constraint.
                Some(con) => sql(steps, drop_constraint(&t, con)),
                None => sql(steps, format!("DROP INDEX {}", qualified(D, schema, name))),
            },
            AlterOp::AddForeignKey { foreign_key } => sql(
                steps,
                format!("ALTER TABLE {t} ADD {}", fk_clause(D, schema, foreign_key)?),
            ),
            AlterOp::DropForeignKey { name } => sql(steps, drop_constraint(&t, name)),
            AlterOp::SetComment { comment } => sql(
                steps,
                format!("COMMENT ON TABLE {t} IS {}", comment_literal(D, comment)),
            ),
        }
    }
    Ok(())
}

fn drop_constraint(t: &str, name: &str) -> String {
    format!("ALTER TABLE {t} DROP CONSTRAINT {}", quote_ident(D, name))
}

fn add_column(t: &str, column: &ColumnSpec, steps: &mut Vec<Step>) -> AppResult<()> {
    sql(
        steps,
        format!(
            "ALTER TABLE {t} ADD COLUMN {}",
            column_def(D, column, false, true)?
        ),
    );
    if let Some(cm) = comment_of(&column.comment) {
        let col = quote_ident(D, &column.name);
        sql(
            steps,
            format!("COMMENT ON COLUMN {t}.{col} IS {}", literal_for(D, cm)),
        );
    }
    Ok(())
}

/// Only what differs between `o` (as loaded) and `c` (as edited) is changed.
fn modify_column(t: &str, o: &ColumnSpec, c: &ColumnSpec, steps: &mut Vec<Step>) -> AppResult<()> {
    need_name("Every column", &c.name)?;
    need_type(c)?;
    let col = quote_ident(D, &c.name);
    let alter = |what: &str| format!("ALTER TABLE {t} ALTER COLUMN {col} {what}");
    if o.name != c.name {
        let from = quote_ident(D, &o.name);
        sql(
            steps,
            format!("ALTER TABLE {t} RENAME COLUMN {from} TO {col}"),
        );
    }
    if !same_type(&o.data_type, &c.data_type) {
        let ty = c.data_type.trim();
        sql(steps, alter(&format!("TYPE {ty} USING {col}::{ty}")));
    }
    if o.nullable != c.nullable {
        sql(
            steps,
            alter(if c.nullable {
                "DROP NOT NULL"
            } else {
                "SET NOT NULL"
            }),
        );
    }
    modify_default_and_identity(o, c, &alter, steps);
    if comment_of(&o.comment) != comment_of(&c.comment) {
        let v = comment_literal(D, &c.comment);
        sql(steps, format!("COMMENT ON COLUMN {t}.{col} IS {v}"));
    }
    Ok(())
}

/// Identity columns have no default of their own; a serial column's default is its
/// sequence, which goes away with the default.
fn modify_default_and_identity(
    o: &ColumnSpec,
    c: &ColumnSpec,
    alter: &impl Fn(&str) -> String,
    steps: &mut Vec<Step>,
) {
    let serial_default =
        o.auto_increment && default_expr(o).is_some_and(|x| x.starts_with("nextval("));
    if !(o.auto_increment && c.auto_increment) && !same_default(o, c) {
        match default_expr(c) {
            Some(x) if !c.auto_increment => sql(steps, alter(&format!("SET DEFAULT {x}"))),
            _ => sql(steps, alter("DROP DEFAULT")),
        }
    }
    if !o.auto_increment && c.auto_increment {
        if c.nullable {
            sql(steps, alter("SET NOT NULL"));
        }
        sql(steps, alter("ADD GENERATED BY DEFAULT AS IDENTITY"));
    } else if o.auto_increment && !c.auto_increment && !serial_default {
        sql(steps, alter("DROP IDENTITY IF EXISTS"));
    }
}

fn set_primary_key(t: &str, columns: &[String], ctx: &Ctx, steps: &mut Vec<Step>) {
    if let Some(pk) = &ctx.primary_key {
        sql(steps, drop_constraint(t, pk));
    }
    if !columns.is_empty() {
        sql(
            steps,
            format!(
                "ALTER TABLE {t} ADD PRIMARY KEY ({})",
                quoted_list(D, columns)
            ),
        );
    }
}
