//! Validation and the SQL fragments shared by every statement: column definitions,
//! foreign key clauses, indexes and quoted lists.

use crate::db::sql::{literal_for, qualified, quote_ident};
use crate::error::{AppError, AppResult};
use crate::models::Dialect;

use super::plan::Step;
use super::spec::{ColumnSpec, ForeignKeySpec, IndexSpec};

const FK_ACTIONS: &[&str] = &[
    "NO ACTION",
    "RESTRICT",
    "CASCADE",
    "SET NULL",
    "SET DEFAULT",
];

/// Longest identifier Postgres keeps; generated index names are cut to it.
const MAX_IDENT_LEN: usize = 63;

pub(super) const SQLITE_AUTOINCREMENT_RULE: &str =
    "In SQLite, only a single INTEGER PRIMARY KEY column can auto-increment.";

pub(super) fn bad(msg: impl Into<String>) -> AppError {
    AppError::validation(msg)
}

pub(super) fn need_name(what: &str, name: &str) -> AppResult<()> {
    if name.trim().is_empty() {
        return Err(bad(format!("{what} needs a name.")));
    }
    if name.contains('\0') {
        return Err(bad(format!("{what} name can't contain a NUL character.")));
    }
    Ok(())
}

/// Option words that are spliced into SQL (charset, encoding…) must be plain words.
pub(super) fn need_word(what: &str, v: &str) -> AppResult<()> {
    if v.chars()
        .all(|c| c.is_ascii_alphanumeric() || c == '_' || c == '-')
    {
        Ok(())
    } else {
        Err(bad(format!(
            "{what} \"{v}\" may only contain letters, digits, '_' and '-'."
        )))
    }
}

pub(super) fn need_type(c: &ColumnSpec) -> AppResult<()> {
    if c.data_type.trim().is_empty() {
        return Err(bad(format!("Column \"{}\" needs a type.", c.name)));
    }
    Ok(())
}

pub(super) fn default_expr(c: &ColumnSpec) -> Option<&str> {
    c.default
        .as_deref()
        .map(str::trim)
        .filter(|d| !d.is_empty())
}

pub(super) fn comment_of(c: &Option<String>) -> Option<&str> {
    c.as_deref().filter(|s| !s.is_empty())
}

/// A comment as a literal, or NULL to remove it.
pub(super) fn comment_literal(driver: Dialect, c: &Option<String>) -> String {
    comment_of(c)
        .map(|x| literal_for(driver, x))
        .unwrap_or_else(|| "NULL".into())
}

fn is_pg_serial(ty: &str) -> bool {
    matches!(
        ty.trim().to_ascii_lowercase().as_str(),
        "serial" | "bigserial" | "smallserial" | "serial2" | "serial4" | "serial8"
    )
}

fn is_now_keyword(expr: &str) -> bool {
    let l = expr.trim().to_ascii_lowercase();
    [
        "current_timestamp",
        "current_date",
        "current_time",
        "localtimestamp",
        "localtime",
        "now()",
    ]
    .iter()
    .any(|k| l.starts_with(k))
}

/// SQLite and MySQL need parentheses around a default that calls a function.
fn wrap_default(driver: Dialect, expr: &str) -> String {
    let t = expr.trim();
    if driver == Dialect::Postgres || t.starts_with('(') || is_now_keyword(t) || !t.contains('(') {
        t.to_string()
    } else {
        format!("({t})")
    }
}

pub(super) fn same_type(a: &str, b: &str) -> bool {
    let normalize = |s: &str| s.split_whitespace().collect::<Vec<_>>().join(" ");
    normalize(a).eq_ignore_ascii_case(&normalize(b))
}

pub(super) fn same_default(a: &ColumnSpec, b: &ColumnSpec) -> bool {
    default_expr(a) == default_expr(b)
}

pub(super) fn quoted_list(driver: Dialect, names: &[String]) -> String {
    names
        .iter()
        .map(|n| quote_ident(driver, n))
        .collect::<Vec<_>>()
        .join(", ")
}

fn fk_action(what: &str, v: &str) -> AppResult<Option<String>> {
    let up = v.trim().to_ascii_uppercase();
    if up.is_empty() {
        return Ok(None);
    }
    if !FK_ACTIONS.contains(&up.as_str()) {
        return Err(bad(format!("Unknown {what} action \"{v}\".")));
    }
    Ok(Some(up))
}

/// A column definition for CREATE TABLE / ADD COLUMN / MySQL CHANGE COLUMN.
/// `inline_pk` puts PRIMARY KEY on the column itself (SQLite AUTOINCREMENT, MySQL
/// ADD COLUMN with AUTO_INCREMENT); `unique` is left out when changing a column.
pub(super) fn column_def(
    driver: Dialect,
    c: &ColumnSpec,
    inline_pk: bool,
    with_unique: bool,
) -> AppResult<String> {
    need_name("Every column", &c.name)?;
    need_type(c)?;
    let mut s = format!("{} {}", quote_ident(driver, &c.name), c.data_type.trim());
    let unique = c.unique && with_unique;
    match driver {
        Dialect::Postgres => pg_column_options(&mut s, c, inline_pk, unique),
        Dialect::Mysql => mysql_column_options(&mut s, c, inline_pk, unique),
        Dialect::Sqlite => sqlite_column_options(&mut s, c, inline_pk, unique),
    }
    Ok(s)
}

fn pg_column_options(s: &mut String, c: &ColumnSpec, inline_pk: bool, unique: bool) {
    if c.auto_increment && !is_pg_serial(&c.data_type) {
        s.push_str(" GENERATED BY DEFAULT AS IDENTITY");
    }
    if !c.nullable {
        s.push_str(" NOT NULL");
    }
    if let (Some(d), false) = (default_expr(c), c.auto_increment) {
        s.push_str(&format!(" DEFAULT {d}"));
    }
    if unique {
        s.push_str(" UNIQUE");
    }
    if inline_pk {
        s.push_str(" PRIMARY KEY");
    }
}

fn mysql_column_options(s: &mut String, c: &ColumnSpec, inline_pk: bool, unique: bool) {
    let d = Dialect::Mysql;
    s.push_str(if c.nullable { " NULL" } else { " NOT NULL" });
    if let (Some(x), false) = (default_expr(c), c.auto_increment) {
        s.push_str(&format!(" DEFAULT {}", wrap_default(d, x)));
    }
    if c.auto_increment {
        s.push_str(" AUTO_INCREMENT");
    }
    if inline_pk {
        s.push_str(" PRIMARY KEY");
    } else if unique {
        s.push_str(" UNIQUE");
    }
    if let Some(cm) = comment_of(&c.comment) {
        s.push_str(&format!(" COMMENT {}", literal_for(d, cm)));
    }
}

fn sqlite_column_options(s: &mut String, c: &ColumnSpec, inline_pk: bool, unique: bool) {
    if inline_pk {
        s.push_str(" PRIMARY KEY");
        if c.auto_increment {
            s.push_str(" AUTOINCREMENT");
        }
    }
    if !c.nullable {
        s.push_str(" NOT NULL");
    }
    if let Some(d) = default_expr(c) {
        s.push_str(&format!(" DEFAULT {}", wrap_default(Dialect::Sqlite, d)));
    }
    if unique {
        s.push_str(" UNIQUE");
    }
}

pub(super) fn fk_clause(driver: Dialect, schema: &str, fk: &ForeignKeySpec) -> AppResult<String> {
    if fk.columns.is_empty() || fk.columns.len() != fk.ref_columns.len() {
        return Err(bad(
            "A foreign key needs the same number of columns on both sides.",
        ));
    }
    need_name("The referenced table", &fk.ref_table)?;
    let ref_schema = if fk.ref_schema.trim().is_empty() {
        schema
    } else {
        &fk.ref_schema
    };
    let target = match driver {
        // SQLite only references tables of the same database file, by bare name.
        Dialect::Sqlite => quote_ident(driver, &fk.ref_table),
        _ => qualified(driver, ref_schema, &fk.ref_table),
    };
    let mut s = String::new();
    if !fk.name.trim().is_empty() {
        s.push_str(&format!(
            "CONSTRAINT {} ",
            quote_ident(driver, fk.name.trim())
        ));
    }
    s.push_str(&format!(
        "FOREIGN KEY ({}) REFERENCES {target} ({})",
        quoted_list(driver, &fk.columns),
        quoted_list(driver, &fk.ref_columns)
    ));
    for (what, value) in [("ON UPDATE", &fk.on_update), ("ON DELETE", &fk.on_delete)] {
        if let Some(a) = fk_action(what, value)? {
            if a != "NO ACTION" {
                s.push_str(&format!(" {what} {a}"));
            }
        }
    }
    Ok(s)
}

fn index_name(table: &str, idx: &IndexSpec) -> String {
    let given = idx.name.trim();
    if !given.is_empty() {
        return given.to_string();
    }
    let mut n = format!(
        "{table}_{}_{}",
        idx.columns.join("_"),
        if idx.unique { "key" } else { "idx" }
    );
    n.retain(|c| !c.is_whitespace());
    n.chars().take(MAX_IDENT_LEN).collect()
}

pub(super) fn create_index(
    driver: Dialect,
    schema: &str,
    table: &str,
    idx: &IndexSpec,
) -> AppResult<String> {
    if idx.columns.is_empty() {
        return Err(bad("An index needs at least one column."));
    }
    let name = index_name(table, idx);
    let unique = if idx.unique { "UNIQUE " } else { "" };
    let cols = quoted_list(driver, &idx.columns);
    let (index, on) = match driver {
        // SQLite puts the schema on the index name, and the table must be in it.
        Dialect::Sqlite => (qualified(driver, schema, &name), quote_ident(driver, table)),
        _ => (quote_ident(driver, &name), qualified(driver, schema, table)),
    };
    Ok(format!("CREATE {unique}INDEX {index} ON {on} ({cols})"))
}

pub(super) fn sql(steps: &mut Vec<Step>, s: String) {
    steps.push(Step::Sql(s));
}
