//! DDL generation for all three drivers, from the shapes the UI sends.

use super::*;
use crate::db::meta::ForeignKeyInfo;
use crate::models::Dialect;

fn col(name: &str, ty: &str) -> ColumnSpec {
    ColumnSpec {
        name: name.into(),
        data_type: ty.into(),
        nullable: true,
        default: None,
        primary_key: false,
        auto_increment: false,
        unique: false,
        comment: None,
        charset: None,
        collation: None,
        extra: None,
    }
}

fn sqls(plan: &Plan) -> Vec<String> {
    plan.steps
        .iter()
        .map(|s| match s {
            Step::Sql(s) => s.clone(),
            Step::Rebuild(_) => "<rebuild>".into(),
        })
        .collect()
}

fn create(driver: Dialect) -> SchemaChange {
    let mut id = col(
        "id",
        if driver == Dialect::Sqlite {
            "INTEGER"
        } else {
            "bigint"
        },
    );
    id.primary_key = true;
    id.auto_increment = true;
    id.nullable = false;
    let mut name = col("name", "varchar(100)");
    name.nullable = false;
    name.default = Some("'n/a'".into());
    name.comment = Some("Display name".into());
    let mut email = col("email", "text");
    email.unique = true;
    SchemaChange::CreateTable {
        schema: if driver == Dialect::Sqlite {
            "main".into()
        } else {
            "app".into()
        },
        name: "users".into(),
        columns: vec![id, name, email, col("org_id", "bigint")],
        indexes: vec![IndexSpec {
            name: String::new(),
            columns: vec!["name".into()],
            unique: false,
            algorithm: String::new(),
        }],
        foreign_keys: vec![ForeignKeySpec {
            name: "users_org_fk".into(),
            columns: vec!["org_id".into()],
            ref_schema: String::new(),
            ref_table: "orgs".into(),
            ref_columns: vec!["id".into()],
            on_update: String::new(),
            on_delete: "cascade".into(),
        }],
        comment: Some("People".into()),
    }
}

#[test]
fn create_table_postgres() {
    let p = build(
        Dialect::Postgres,
        &create(Dialect::Postgres),
        &Ctx::default(),
    )
    .unwrap();
    assert_eq!(p.exec, Exec::Transaction);
    assert_eq!(
        sqls(&p),
        vec![
            concat!(
                "CREATE TABLE \"app\".\"users\" (\n",
                "  \"id\" bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,\n",
                "  \"name\" varchar(100) NOT NULL DEFAULT 'n/a',\n",
                "  \"email\" text UNIQUE,\n",
                "  \"org_id\" bigint,\n",
                "  PRIMARY KEY (\"id\"),\n",
                "  CONSTRAINT \"users_org_fk\" FOREIGN KEY (\"org_id\") ",
                "REFERENCES \"app\".\"orgs\" (\"id\") ON DELETE CASCADE\n",
                ")"
            ),
            "COMMENT ON TABLE \"app\".\"users\" IS 'People'",
            "COMMENT ON COLUMN \"app\".\"users\".\"name\" IS 'Display name'",
            "CREATE INDEX \"users_name_idx\" ON \"app\".\"users\" (\"name\")",
        ]
    );
}

#[test]
fn create_table_mysql_and_sqlite() {
    let p = build(Dialect::Mysql, &create(Dialect::Mysql), &Ctx::default()).unwrap();
    assert_eq!(p.exec, Exec::Sequential);
    assert_eq!(
        sqls(&p)[0],
        concat!(
            "CREATE TABLE `app`.`users` (\n",
            "  `id` bigint NOT NULL AUTO_INCREMENT,\n",
            "  `name` varchar(100) NOT NULL DEFAULT 'n/a' COMMENT 'Display name',\n",
            "  `email` text NULL UNIQUE,\n",
            "  `org_id` bigint NULL,\n",
            "  PRIMARY KEY (`id`),\n",
            "  CONSTRAINT `users_org_fk` FOREIGN KEY (`org_id`) ",
            "REFERENCES `app`.`orgs` (`id`) ON DELETE CASCADE\n",
            ") COMMENT='People'"
        )
    );
    let p = build(Dialect::Sqlite, &create(Dialect::Sqlite), &Ctx::default()).unwrap();
    assert_eq!(
        sqls(&p),
        vec![
            concat!(
                "CREATE TABLE \"main\".\"users\" (\n",
                "  \"id\" INTEGER PRIMARY KEY AUTOINCREMENT NOT NULL,\n",
                "  \"name\" varchar(100) NOT NULL DEFAULT 'n/a',\n",
                "  \"email\" text UNIQUE,\n",
                "  \"org_id\" bigint,\n",
                "  CONSTRAINT \"users_org_fk\" FOREIGN KEY (\"org_id\") ",
                "REFERENCES \"orgs\" (\"id\") ON DELETE CASCADE\n",
                ")"
            ),
            "CREATE INDEX \"main\".\"users_name_idx\" ON \"users\" (\"name\")",
        ]
    );
}

#[test]
fn rejects_bad_input() {
    let one = |c: Vec<ColumnSpec>| SchemaChange::CreateTable {
        schema: "s".into(),
        name: "t".into(),
        columns: c,
        indexes: vec![],
        foreign_keys: vec![],
        comment: None,
    };
    assert!(build(Dialect::Postgres, &one(vec![]), &Ctx::default()).is_err());
    assert!(build(
        Dialect::Postgres,
        &one(vec![col("", "int")]),
        &Ctx::default()
    )
    .is_err());
    assert!(build(Dialect::Postgres, &one(vec![col("a", "")]), &Ctx::default()).is_err());
    assert!(build(
        Dialect::Postgres,
        &one(vec![col("a", "int"), col("A", "int")]),
        &Ctx::default()
    )
    .is_err());
    // A type that tries to end the statement.
    let err = build(
        Dialect::Postgres,
        &one(vec![col("a", "int); DROP TABLE x; --")]),
        &Ctx::default(),
    )
    .unwrap_err();
    assert!(err.message.contains("stray"), "{}", err.message);
    let mut auto = col("a", "text");
    auto.auto_increment = true;
    assert!(build(Dialect::Sqlite, &one(vec![auto]), &Ctx::default()).is_err());
    let bad_db = SchemaChange::CreateDatabase {
        name: "x".into(),
        options: DatabaseOptions {
            charset: "utf8; drop".into(),
            ..Default::default()
        },
    };
    assert!(build(Dialect::Mysql, &bad_db, &Ctx::default()).is_err());
}

#[test]
fn databases_schemas_and_tables() {
    let ctx = Ctx::default();
    let b = |d, c: SchemaChange| sqls(&build(d, &c, &ctx).unwrap());
    assert_eq!(
        b(
            Dialect::Postgres,
            SchemaChange::CreateDatabase {
                name: "shop".into(),
                options: DatabaseOptions {
                    encoding: "UTF8".into(),
                    template: "template0".into(),
                    ..Default::default()
                }
            }
        ),
        vec!["CREATE DATABASE \"shop\" TEMPLATE \"template0\" ENCODING 'UTF8'"]
    );
    assert_eq!(
        b(
            Dialect::Mysql,
            SchemaChange::CreateDatabase {
                name: "shop".into(),
                options: DatabaseOptions {
                    charset: "utf8mb4".into(),
                    collation: "utf8mb4_unicode_ci".into(),
                    ..Default::default()
                }
            }
        ),
        vec!["CREATE DATABASE `shop` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci"]
    );
    assert_eq!(
        b(
            Dialect::Postgres,
            SchemaChange::DropDatabase {
                name: "shop".into(),
                force: true
            }
        ),
        vec!["DROP DATABASE \"shop\" WITH (FORCE)"]
    );
    assert_eq!(
        b(
            Dialect::Postgres,
            SchemaChange::RenameDatabase {
                from: "shop".into(),
                to: "store".into()
            }
        ),
        vec!["ALTER DATABASE \"shop\" RENAME TO \"store\""]
    );
    let mysql = SchemaChange::RenameDatabase {
        from: "a".into(),
        to: "b".into(),
    };
    assert!(build(Dialect::Mysql, &mysql, &ctx).is_err());
    assert_eq!(
        build(
            Dialect::Postgres,
            &SchemaChange::DropDatabase {
                name: "x".into(),
                force: false
            },
            &ctx
        )
        .unwrap()
        .exec,
        Exec::Sequential
    );
    assert_eq!(
        b(
            Dialect::Postgres,
            SchemaChange::DropSchema {
                name: "old".into(),
                cascade: true
            }
        ),
        vec!["DROP SCHEMA \"old\" CASCADE"]
    );
    assert!(build(
        Dialect::Mysql,
        &SchemaChange::CreateSchema { name: "x".into() },
        &ctx
    )
    .is_err());
    assert_eq!(
        b(
            Dialect::Mysql,
            SchemaChange::RenameTable {
                schema: "s".into(),
                from: "a".into(),
                to: "b".into()
            }
        ),
        vec!["RENAME TABLE `s`.`a` TO `s`.`b`"]
    );
    assert_eq!(
        b(
            Dialect::Sqlite,
            SchemaChange::RenameTable {
                schema: "main".into(),
                from: "a".into(),
                to: "b".into()
            }
        ),
        vec!["ALTER TABLE \"main\".\"a\" RENAME TO \"b\""]
    );
    assert_eq!(
        b(
            Dialect::Sqlite,
            SchemaChange::TruncateTable {
                schema: "main".into(),
                name: "a".into(),
                cascade: false
            }
        ),
        vec!["DELETE FROM \"main\".\"a\""]
    );
    let view = Ctx {
        object_kind: Some("MATERIALIZED VIEW".into()),
        ..Default::default()
    };
    assert_eq!(
        sqls(
            &build(
                Dialect::Postgres,
                &SchemaChange::DropTable {
                    schema: "s".into(),
                    name: "v".into(),
                    cascade: true
                },
                &view
            )
            .unwrap()
        ),
        vec!["DROP MATERIALIZED VIEW \"s\".\"v\" CASCADE"]
    );
    assert_eq!(
        b(
            Dialect::Postgres,
            SchemaChange::DuplicateTable {
                schema: "s".into(),
                from: "a".into(),
                to: "a_copy".into(),
                with_data: true
            }
        ),
        vec![
            "CREATE TABLE \"s\".\"a_copy\" (LIKE \"s\".\"a\" INCLUDING ALL)",
            "INSERT INTO \"s\".\"a_copy\" OVERRIDING SYSTEM VALUE SELECT * FROM \"s\".\"a\""
        ]
    );
}

fn alter(driver: Dialect, ops: Vec<AlterOp>, ctx: &Ctx) -> Plan {
    build(
        driver,
        &SchemaChange::AlterTable {
            schema: "s".into(),
            name: "t".into(),
            ops,
            rename_to: None,
        },
        ctx,
    )
    .unwrap()
}

#[test]
fn alter_postgres() {
    let mut o = col("qty", "integer");
    o.default = Some("0".into());
    let mut c = col("quantity", "bigint");
    c.nullable = false;
    c.comment = Some("Units".into());
    let ctx = Ctx {
        primary_key: Some("t_pkey".into()),
        index_constraints: [("t_email_key".to_string(), "t_email_key".to_string())].into(),
        ..Default::default()
    };
    let p = alter(
        Dialect::Postgres,
        vec![
            AlterOp::AddIndex {
                index: IndexSpec {
                    name: "t_q".into(),
                    columns: vec!["quantity".into()],
                    unique: true,
                    algorithm: String::new(),
                },
            },
            AlterOp::ModifyColumn {
                original: o,
                column: c,
                position: None,
            },
            AlterOp::DropIndex {
                name: "t_email_key".into(),
            },
            AlterOp::DropIndex {
                name: "t_plain".into(),
            },
            AlterOp::SetPrimaryKey {
                columns: vec!["id".into(), "quantity".into()],
            },
            AlterOp::DropColumn { name: "old".into() },
        ],
        &ctx,
    );
    assert_eq!(
        sqls(&p),
        vec![
            "ALTER TABLE \"s\".\"t\" DROP CONSTRAINT \"t_email_key\"",
            "DROP INDEX \"s\".\"t_plain\"",
            "ALTER TABLE \"s\".\"t\" DROP COLUMN \"old\"",
            "ALTER TABLE \"s\".\"t\" RENAME COLUMN \"qty\" TO \"quantity\"",
            concat!(
                "ALTER TABLE \"s\".\"t\" ALTER COLUMN \"quantity\" ",
                "TYPE bigint USING \"quantity\"::bigint"
            ),
            "ALTER TABLE \"s\".\"t\" ALTER COLUMN \"quantity\" SET NOT NULL",
            "ALTER TABLE \"s\".\"t\" ALTER COLUMN \"quantity\" DROP DEFAULT",
            "COMMENT ON COLUMN \"s\".\"t\".\"quantity\" IS 'Units'",
            "ALTER TABLE \"s\".\"t\" DROP CONSTRAINT \"t_pkey\"",
            "ALTER TABLE \"s\".\"t\" ADD PRIMARY KEY (\"id\", \"quantity\")",
            "CREATE UNIQUE INDEX \"t_q\" ON \"s\".\"t\" (\"quantity\")",
        ]
    );
    // Identity on and off; serial off drops only the default.
    let base = col("id", "integer");
    let mut auto = base.clone();
    auto.auto_increment = true;
    assert_eq!(
        sqls(&alter(
            Dialect::Postgres,
            vec![AlterOp::ModifyColumn {
                original: base.clone(),
                column: auto.clone(),
                position: None,
            }],
            &Ctx::default()
        )),
        vec![
            "ALTER TABLE \"s\".\"t\" ALTER COLUMN \"id\" SET NOT NULL",
            "ALTER TABLE \"s\".\"t\" ALTER COLUMN \"id\" ADD GENERATED BY DEFAULT AS IDENTITY"
        ]
    );
    assert_eq!(
        sqls(&alter(
            Dialect::Postgres,
            vec![AlterOp::ModifyColumn {
                original: auto.clone(),
                column: base.clone(),
                position: None,
            }],
            &Ctx::default()
        )),
        vec!["ALTER TABLE \"s\".\"t\" ALTER COLUMN \"id\" DROP IDENTITY IF EXISTS"]
    );
    let mut serial = auto.clone();
    serial.default = Some("nextval('t_id_seq'::regclass)".into());
    assert_eq!(
        sqls(&alter(
            Dialect::Postgres,
            vec![AlterOp::ModifyColumn {
                original: serial,
                column: base,
                position: None,
            }],
            &Ctx::default()
        )),
        vec!["ALTER TABLE \"s\".\"t\" ALTER COLUMN \"id\" DROP DEFAULT"]
    );
}

#[test]
fn alter_mysql() {
    let mut o = col("name", "varchar(50)");
    o.default = Some("'x'".into());
    let mut c = o.clone();
    c.data_type = "varchar(200)".into();
    let unchanged = col("same", "int");
    let mut id = col("id", "int");
    id.auto_increment = true;
    id.nullable = false;
    id.primary_key = true;
    let p = alter(
        Dialect::Mysql,
        vec![
            AlterOp::ModifyColumn {
                original: o,
                column: c,
                position: None,
            },
            AlterOp::ModifyColumn {
                original: unchanged.clone(),
                column: unchanged,
                position: None,
            },
            AlterOp::AddColumn {
                column: id,
                position: None,
            },
            AlterOp::SetPrimaryKey {
                columns: vec!["id".into()],
            },
            AlterOp::DropForeignKey { name: "fk1".into() },
            AlterOp::SetComment {
                comment: Some("it's".into()),
            },
        ],
        &Ctx::default(),
    );
    assert_eq!(
        sqls(&p),
        vec![
            "ALTER TABLE `s`.`t` DROP FOREIGN KEY `fk1`",
            "ALTER TABLE `s`.`t` CHANGE COLUMN `name` `name` varchar(200) NULL DEFAULT 'x'",
            "ALTER TABLE `s`.`t` ADD COLUMN `id` int NOT NULL AUTO_INCREMENT PRIMARY KEY",
            "ALTER TABLE `s`.`t` COMMENT = 'it''s'",
        ]
    );
    let had = Ctx {
        primary_key: Some("PRIMARY".into()),
        ..Default::default()
    };
    assert_eq!(
        sqls(&alter(
            Dialect::Mysql,
            vec![AlterOp::SetPrimaryKey {
                columns: vec!["a".into(), "b".into()]
            }],
            &had
        )),
        vec!["ALTER TABLE `s`.`t` DROP PRIMARY KEY, ADD PRIMARY KEY (`a`, `b`)"]
    );
    // A function default needs parentheses on MySQL.
    let mut u = col("u", "char(36)");
    u.default = Some("uuid()".into());
    assert_eq!(
        sqls(&alter(
            Dialect::Mysql,
            vec![AlterOp::AddColumn {
                column: u,
                position: None,
            }],
            &Ctx::default()
        )),
        vec!["ALTER TABLE `s`.`t` ADD COLUMN `u` char(36) NULL DEFAULT (uuid())"]
    );
}

#[test]
fn alter_sqlite_in_place_or_rebuild() {
    let o = col("a", "TEXT");
    let mut renamed = o.clone();
    renamed.name = "b".into();
    let p = alter(
        Dialect::Sqlite,
        vec![
            AlterOp::ModifyColumn {
                original: o.clone(),
                column: renamed.clone(),
                position: None,
            },
            AlterOp::AddColumn {
                column: col("c", "INTEGER"),
                position: None,
            },
            AlterOp::DropColumn { name: "d".into() },
            AlterOp::AddIndex {
                index: IndexSpec {
                    name: "t_c".into(),
                    columns: vec!["c".into()],
                    unique: false,
                    algorithm: String::new(),
                },
            },
        ],
        &Ctx::default(),
    );
    assert_eq!(p.exec, Exec::Transaction);
    assert_eq!(
        sqls(&p),
        vec![
            "ALTER TABLE \"s\".\"t\" DROP COLUMN \"d\"",
            "ALTER TABLE \"s\".\"t\" RENAME COLUMN \"a\" TO \"b\"",
            "ALTER TABLE \"s\".\"t\" ADD COLUMN \"c\" INTEGER",
            "CREATE INDEX \"s\".\"t_c\" ON \"t\" (\"c\")",
        ]
    );
    let mut typed = renamed.clone();
    typed.data_type = "INTEGER".into();
    typed.nullable = false;
    let p = alter(
        Dialect::Sqlite,
        vec![AlterOp::ModifyColumn {
            original: o,
            column: typed,
            position: None,
        }],
        &Ctx::default(),
    );
    assert_eq!(p.exec, Exec::SqliteRebuild);
    assert_eq!(
        sqls(&p),
        vec![
            "ALTER TABLE \"s\".\"t\" RENAME COLUMN \"a\" TO \"b\"",
            "<rebuild>"
        ]
    );
    let Step::Rebuild(r) = &p.steps[1] else {
        panic!()
    };
    assert_eq!(r.renames, vec![("a".to_string(), "b".to_string())]);
    assert!(matches!(&r.ops[0], AlterOp::ModifyColumn { original, .. } if original.name == "b"));
}

#[test]
fn sqlite_rebuild_keeps_constraints() {
    let table_sql = concat!(
        "CREATE TABLE \"items\" (\n",
        "  id INTEGER PRIMARY KEY AUTOINCREMENT,\n",
        "  qty TEXT NOT NULL DEFAULT '1' CHECK (qty <> ''),\n",
        "  owner INTEGER REFERENCES people(id) ON DELETE CASCADE,\n",
        "  label TEXT COLLATE NOCASE,\n",
        "  gone TEXT,\n",
        "  UNIQUE (label)\n",
        ")"
    );
    let mut qty = col("qty", "TEXT");
    qty.nullable = false;
    qty.default = Some("'1'".into());
    let mut qty2 = qty.clone();
    qty2.data_type = "INTEGER".into();
    qty2.default = Some("1".into());
    let spec = Rebuild {
        schema: "main".into(),
        table: "items".into(),
        ops: vec![
            AlterOp::ModifyColumn {
                original: qty,
                column: qty2,
                position: None,
            },
            AlterOp::DropColumn {
                name: "gone".into(),
            },
            AlterOp::AddColumn {
                column: col("note", "TEXT"),
                position: None,
            },
            AlterOp::AddForeignKey {
                foreign_key: ForeignKeySpec {
                    name: String::new(),
                    columns: vec!["label".into()],
                    ref_schema: String::new(),
                    ref_table: "labels".into(),
                    ref_columns: vec!["name".into()],
                    on_update: String::new(),
                    on_delete: String::new(),
                },
            },
        ],
        renames: vec![],
    };
    let objects = vec![
        SqliteObject {
            name: "items_label".into(),
            sql: "CREATE INDEX items_label ON items(label)".into(),
            columns: vec!["label".into()],
        },
        SqliteObject {
            name: "items_gone".into(),
            sql: "CREATE INDEX items_gone ON items(gone)".into(),
            columns: vec!["gone".into()],
        },
    ];
    let out = sqlite_rebuild_sql(&spec, table_sql, &objects, &[]).unwrap();
    assert_eq!(
        out[0],
        concat!(
            "CREATE TABLE \"main\".\"_libratable_new_items\" (\n",
            "  id INTEGER PRIMARY KEY AUTOINCREMENT,\n",
            "  \"qty\" INTEGER NOT NULL DEFAULT 1 CHECK (qty <> ''),\n",
            "  owner INTEGER REFERENCES people (id) ON DELETE CASCADE,\n",
            "  label TEXT COLLATE NOCASE,\n",
            "  \"note\" TEXT,\n",
            "  UNIQUE (label),\n",
            "  FOREIGN KEY (\"label\") REFERENCES \"labels\"(\"name\")\n",
            ")"
        )
    );
    assert_eq!(
        out[1],
        concat!(
            "INSERT INTO \"main\".\"_libratable_new_items\" ",
            "(\"id\", \"qty\", \"owner\", \"label\") ",
            "SELECT \"id\", \"qty\", \"owner\", \"label\" FROM \"main\".\"items\""
        )
    );
    assert_eq!(out[2], "DROP TABLE \"main\".\"items\"");
    assert_eq!(
        out[4],
        "ALTER TABLE \"main\".\"_libratable_new_items\" RENAME TO \"items\""
    );
    assert_eq!(out[6], "CREATE INDEX items_label ON items(label)");
    assert!(out[7].starts_with("-- index \"items_gone\" is not recreated"));

    // New composite primary key; dropping a column-level REFERENCES.
    let fk = ForeignKeyInfo {
        name: "fk_0".into(),
        columns: vec!["owner".into()],
        ref_table: "people".into(),
        ref_columns: vec!["id".into()],
        on_update: "NO ACTION".into(),
        on_delete: "CASCADE".into(),
        definition: String::new(),
    };
    let spec = Rebuild {
        schema: "main".into(),
        table: "items".into(),
        ops: vec![
            AlterOp::SetPrimaryKey {
                columns: vec!["id".into(), "label".into()],
            },
            AlterOp::DropForeignKey {
                name: "fk_0".into(),
            },
        ],
        renames: vec![],
    };
    let out = sqlite_rebuild_sql(&spec, table_sql, &[], &[fk]).unwrap();
    assert!(out[0].contains("  id INTEGER,\n"), "{}", out[0]);
    assert!(out[0].contains("  owner INTEGER,\n"), "{}", out[0]);
    assert!(
        out[0].contains("PRIMARY KEY (\"id\", \"label\")"),
        "{}",
        out[0]
    );
}

#[test]
fn sqlite_copy_renames_table() {
    let s = sqlite_copy_sql(
        "CREATE TABLE t (id INTEGER PRIMARY KEY, a TEXT)",
        "main",
        "t_copy",
    )
    .unwrap();
    assert_eq!(
        s,
        "CREATE TABLE \"main\".\"t_copy\" (id INTEGER PRIMARY KEY, a TEXT)"
    );
}

#[test]
fn deserializes_from_the_ui() {
    let v = serde_json::json!({
        "kind": "alter_table", "schema": "public", "name": "t",
        "ops": [
            { "op": "modify_column",
              "original": {
                  "name": "a", "dataType": "int", "nullable": true, "default": null,
                  "primaryKey": false, "autoIncrement": false
              },
              "column": { "name": "a", "dataType": "bigint", "nullable": false } },
            { "op": "add_foreign_key",
              "foreignKey": {
                  "columns": ["b"], "refTable": "x", "refColumns": ["id"], "onDelete": "SET NULL"
              } },
            { "op": "set_primary_key", "columns": ["a"] }
        ]
    });
    let c: SchemaChange = serde_json::from_value(v).unwrap();
    let p = build(Dialect::Postgres, &c, &Ctx::default()).unwrap();
    assert_eq!(sqls(&p).len(), 4);
}
